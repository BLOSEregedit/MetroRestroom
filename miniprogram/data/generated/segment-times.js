function segmentKey(fromLineStationId, toLineStationId) {
  return String(fromLineStationId || '') + '>' + String(toLineStationId || '');
}

function headwayKey(lineId, routeId, directionId) {
  return [lineId, routeId, directionId].map(function (value) { return String(value || ''); }).join(':');
}

function hasSourcedSegment(fromLineStationId, toLineStationId) {
  return Object.prototype.hasOwnProperty.call(DATA.segments, segmentKey(fromLineStationId, toLineStationId));
}

function getSegmentSeconds(fromLineStationId, toLineStationId) {
  const key = segmentKey(fromLineStationId, toLineStationId);
  return hasSourcedSegment(fromLineStationId, toLineStationId)
    ? DATA.segments[key]
    : DATA.defaults.segmentSeconds;
}

function getHeadwaySeconds(lineId, routeId, directionId) {
  const key = headwayKey(lineId, routeId, directionId);
  return Object.prototype.hasOwnProperty.call(DATA.headways, key)
    ? DATA.headways[key]
    : DATA.defaults.headwaySeconds;
}

function getExpectedWaitSeconds(lineId, routeId, directionId) {
  return Math.round(getHeadwaySeconds(lineId, routeId, directionId) / 2);
}

